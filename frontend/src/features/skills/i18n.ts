function harnessLabel(harness: string): string {
  return harness.length > 0 ? `${harness[0].toUpperCase()}${harness.slice(1)}` : harness;
}

function formatPackageStatus(value: string): string {
  return value
    .replace(/[-_]/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function formatDeploymentAction(value: string): string {
  return value.length > 0 ? `${value[0].toUpperCase()}${value.slice(1)}` : value;
}
